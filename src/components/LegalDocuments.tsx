/**
 * 利用規約とプライバシーポリシーの本文（Issue #64）。
 *
 * ページ（/terms・/privacy）、各役割のヘルプ、使いはじめの同意のモーダルの
 * 3 か所で同じものを出す。書き写すと食い違うので、本文はここだけに置く。
 *
 * ★ 本文を改めたら lib/legal.ts の LEGAL_VERSION を上げる ★
 * 上げると、参加者と酒蔵にもう一度同意を求める。
 *
 * 事業者は「本イベントの主催者」、連絡先はアプリ内の問い合わせ機能にしている。
 * 主催者が変わっても本文を書き換えずに使えるように。公開の前に、実際の運営に
 * 合っているかを主催者が確かめ、必要なら専門家に見てもらうこと（DESIGN.md）。
 */

function H2({ children }: { children: ReactNode }) {
  return <h2 className="mt-6 mb-2 font-display text-[17px] tracking-[0.04em] text-ink">{children}</h2>;
}

function P({ children }: { children: ReactNode }) {
  return <p className="mb-2 text-[13px] leading-[1.9] text-ink-70">{children}</p>;
}

function Ol({ children }: { children: ReactNode }) {
  return (
    <ol className="mb-2 flex list-decimal flex-col gap-1.5 pl-5 text-[13px] leading-[1.9] text-ink-70">
      {children}
    </ol>
  );
}

function Ul({ children }: { children: ReactNode }) {
  return (
    <ul className="mb-2 flex list-disc flex-col gap-1.5 pl-5 text-[13px] leading-[1.9] text-ink-70">
      {children}
    </ul>
  );
}

/** 表。スマホで横にはみ出さないよう、行ごとに縦に積む形にする。 */
function Rows({ rows }: { rows: { head: string; items: [string, string][] }[] }) {
  return (
    <div className="mb-2 flex flex-col gap-2">
      {rows.map((row) => (
        <div key={row.head} className="rounded-field border border-hairline bg-ink/5 px-3.5 py-2.5">
          <div className="mb-1 text-[13px] font-bold text-ink">{row.head}</div>
          <dl className="grid grid-cols-[auto_1fr] gap-x-3 gap-y-1 text-[12px] leading-[1.7]">
            {row.items.map(([k, v]) => (
              <div key={k} className="contents">
                <dt className="whitespace-nowrap text-ink-45">{k}</dt>
                <dd className="text-ink-70">{v}</dd>
              </div>
            ))}
          </dl>
        </div>
      ))}
    </div>
  );
}

